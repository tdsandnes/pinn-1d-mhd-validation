from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import h5py
import numpy as np
import torch
import yaml
from pinninit import (
    CartesianCoords,
    Coords,
    Field,
    make_coords_dataclass,
    make_field_dataclass,
)

from plotting.pinn_utils import evaluate_pinn_u_b, load_pinn
from plotting.plotting_utils import n_parameters_from_yaml


@dataclass
class TestData:
    """Test data coordinates and fields."""

    coords: Coords
    u: Field
    b: Field


@dataclass
class TestError:
    """Model error on test set."""

    error_u: float
    error_b: float
    n_parameters: int
    yaml_path: Path

    @property
    def mean_error(self) -> float:
        return 0.5 * (self.error_u + self.error_b)


def load_test_data(
    test_filepath: Path,
    device: torch.device,
    dataset_label: str = "test",
    role: str = "test",
    t_min: float | None = None,
    t_max: float | None = None,
) -> TestData:
    """A simulation's test set, over the times requested."""
    with h5py.File(test_filepath, "r") as f:
        group = f[dataset_label][role]
        x = group["Coords"]["x"][:]
        t = group["Coords"]["t"][:]
        b = group["Fields"]["b"][:]
        u = group["Fields"]["u"][:]

    # Restrict the test set to the requested time interval
    mask = np.ones_like(t, dtype=bool)
    if t_min is not None:
        mask &= t >= t_min
    if t_max is not None:
        mask &= t <= t_max
    if not mask.any():
        raise ValueError(f"No test points in [{t_min}, {t_max}] in {test_filepath}")

    # Make coords object
    coord_system = CartesianCoords(coord_axes={"x"}, device=device)
    XTCoords = make_coords_dataclass({"x", "t"}, coord_system, device)
    coords = XTCoords(
        x=torch.tensor(x[mask], device=device, requires_grad=True),
        t=torch.tensor(t[mask], device=device, requires_grad=True),
    )

    # Make fields bound to coords
    ScalarField = make_field_dataclass(0, XTCoords)
    u = ScalarField(
        label="u", coords=coords, value=torch.tensor(u[mask], device=device)
    )
    b = ScalarField(
        label="b", coords=coords, value=torch.tensor(b[mask], device=device)
    )

    return TestData(coords=coords, u=u, b=b)


def relative_error(pred: torch.Tensor, true: torch.Tensor) -> float:
    return float(
        torch.sqrt(torch.sum((pred - true) ** 2)) / torch.sqrt(torch.sum(true**2))
    )


def model_errors(
    param_dir: Path,
    model_dir: Path,
    test: TestData,
    n_batches: int = 1,
    model_filter: Callable[[str], bool] | None = None,
) -> dict[str, TestError]:
    """The test error of every trained model in a suite, keyed by model name."""
    yaml_paths = sorted(param_dir.glob("*.yml"))
    if not yaml_paths:
        raise RuntimeError(f"No parameter files in {param_dir.resolve()}")

    u_true = test.u.tensor(test.coords)
    b_true = test.b.tensor(test.coords)

    # Evaluate every trained model generated by the suite
    test_errors: dict[str, TestError] = {}
    for yaml_path in yaml_paths:
        name = yaml.safe_load(yaml_path.read_text())["model_name"]
        if model_filter is not None and not model_filter(name):
            continue

        model_path = model_dir / f"{name}.pth"
        if not model_path.exists():
            print(f"Model not found: {model_path}")
            continue

        print(f"Evaluating error for {name}")

        # Load the model using the parameter file that generated it
        pinn = load_pinn(yaml_path, model_path, test.coords.device)

        # Evaluate predicted u and b
        u_pred, b_pred = evaluate_pinn_u_b(pinn, test.coords, n_batches)

        test_errors[name] = TestError(
            error_u=relative_error(u_pred, u_true),
            error_b=relative_error(b_pred, b_true),
            n_parameters=n_parameters_from_yaml(yaml_path),
            yaml_path=yaml_path,
        )

        # Free up memory
        del pinn
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    if not test_errors:
        raise RuntimeError(f"No trained models found in {model_dir.resolve()}")
    return test_errors


def pointwise_errors(
    param_dir: Path,
    model_dir: Path,
    test: TestData,
    n_batches: int = 1,
    model_filter: Callable[[str], bool] | None = None,
) -> dict[str, tuple[np.ndarray, np.ndarray]]:
    """Absolute pointwise u and b errors for every matching trained model."""

    # Get the true fields once so they can be reused for every model
    u_true = test.u.tensor(test.coords)
    b_true = test.b.tensor(test.coords)

    # Find all parameter files generated for the suite
    yaml_paths = sorted(param_dir.glob("*.yml"))
    if not yaml_paths:
        raise RuntimeError(f"No parameter files in {param_dir.resolve()}")

    errors: dict[str, tuple[np.ndarray, np.ndarray]] = {}

    # Evaluate each selected trained model at every test point
    for yaml_path in yaml_paths:
        name = yaml.safe_load(yaml_path.read_text())["model_name"]

        if model_filter is not None and not model_filter(name):
            continue

        model_path = model_dir / f"{name}.pth"
        if not model_path.exists():
            print(f"Model not found: {model_path}")
            continue

        print(f"Evaluating per-point error for {name}")

        # Load the model and evaluate both predicted fields
        pinn = load_pinn(yaml_path, model_path, test.coords.device)
        u_pred, b_pred = evaluate_pinn_u_b(pinn, test.coords, n_batches)

        # Store the absolute error at each test point
        errors[name] = (
            torch.abs(u_pred - u_true).cpu().numpy(),
            torch.abs(b_pred - b_true).cpu().numpy(),
        )

        # Free the model before evaluating the next one
        del pinn
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    if not errors:
        raise RuntimeError(f"No trained models found in {model_dir.resolve()}")

    return errors
